// Dependency-free packaging for GitHub Pages. Keep committed release directories
// immutable: changed sources produce a different path, not a query-string suffix.
import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const hash = data => createHash('sha256').update(data).digest('hex');
const read = name => readFile(path.join(root, name));
const modules = (await readdir(path.join(root, 'js'))).filter(name => name.endsWith('.js')).sort();
const sources = new Map();
for (const name of modules) sources.set(`js/${name}`, await read(`js/${name}`));
sources.set('styles.css', await read('styles.css'));
for (const name of ['index.html', 'demo.html']) {
  // The HTML remains editable in place; normalize generated references for a
  // deterministic digest without a self-referential build hash.
  const html = (await read(name)).toString().replace(/\.\/assets\/[a-f0-9]{20}\//g, './');
  sources.set(name, Buffer.from(html));
}
const template = (await read('scripts/service-worker.js')).toString();
const fixed = new Map();
for (const name of ['manifest.webmanifest', ...(await readdir(path.join(root, 'icons'))).sort().map(name => `icons/${name}`)]) fixed.set(name, await read(name));
const version = sources.get('js/version.js').toString().match(/APP_VERSION = '([^']+)'/)[1];
const build = hash(Buffer.concat([...sources, ...fixed].flatMap(([name, data]) => [Buffer.from(name + '\0'), data, Buffer.from('\0')]).concat(Buffer.from(template), await read('scripts/build-release.mjs')))).slice(0, 20);
const prefix = `assets/${build}/`;
const outputs = new Map();
for (const [name, data] of sources) {
  if (name.endsWith('.html')) {
    outputs.set(name, Buffer.from(data.toString().replace(/(src|href)="\.\/(js\/[^" ]+\.js|styles\.css)"/g, `$1="./${prefix}$2"`)));
  } else {
    const released = name === 'js/version.js' ? Buffer.from(data.toString().replace("BUILD_ID = 'source'", `BUILD_ID = '${build}'`)) : data;
    outputs.set(prefix + name, released);
  }
}
for (const [name, data] of fixed) outputs.set(name, data);
const assets = [...outputs].map(([name, data]) => ({ url: './' + name, sha256: hash(data) }));
assets.unshift({ url: './', sha256: hash(outputs.get('index.html')) });
const release = { version, build, assets };
outputs.set('release-manifest.json', Buffer.from(JSON.stringify(release, null, 2) + '\n'));
outputs.set('sw.js', Buffer.from('// Generated by scripts/build-release.mjs. Edit the sources, then regenerate.\n' + template.replace('__RELEASE__', JSON.stringify(release, null, 2))));
for (const [name, data] of outputs) {
  if (check) {
    let existing;
    try { existing = await read(name); } catch { throw new Error(`Missing release file: ${name}. Run npm run release.`); }
    if (!existing.equals(data)) throw new Error(`Stale release file: ${name}. Run npm run release.`);
  } else {
    await mkdir(path.dirname(path.join(root, name)), { recursive: true });
    await writeFile(path.join(root, name), data);
  }
}
console.log(`${check ? 'Verified' : 'Generated'} app ${version}, build ${build}, ${assets.length} cache entries.`);
